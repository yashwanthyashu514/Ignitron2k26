import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

// Generate Coordinator Final Report PDF
export function generateCoordinatorReportPDF({
  eventName,
  coordinatorName,
  submissionDate,
  teams = [],
  scoringCriteria = [],
  status = 'Submitted',
}) {
  const doc = new jsPDF({
    orientation: 'landscape',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();

  // Primary Header Banner
  doc.setFillColor(15, 23, 42); // Slate 900
  doc.rect(0, 0, pageWidth, 75, 'F');

  // Accent Line
  doc.setFillColor(245, 158, 11); // Amber / Gold
  doc.rect(0, 72, pageWidth, 3, 'F');

  // Brand Titles
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.setTextColor(245, 158, 11);
  doc.text('IGNITRON 2K26', 40, 36);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(148, 163, 184);
  doc.text('GM UNIVERSITY · GMUSA · NATIONAL LEVEL TECH FEST', 40, 52);

  // Document Badge
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.setTextColor(255, 255, 255);
  doc.text('COORDINATOR OFFICIAL FINAL EVENT REPORT', pageWidth - 40, 42, { align: 'right' });

  // Event & Coordinator Info Card
  doc.setFillColor(248, 250, 252);
  doc.roundedRect(40, 90, pageWidth - 80, 50, 4, 4, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(30, 41, 59);
  doc.text('EVENT:', 55, 110);
  doc.setFont('helvetica', 'normal');
  doc.text(eventName || 'N/A', 110, 110);

  doc.setFont('helvetica', 'bold');
  doc.text('COORDINATOR:', 55, 126);
  doc.setFont('helvetica', 'normal');
  doc.text(coordinatorName || 'Assigned Coordinator', 145, 126);

  doc.setFont('helvetica', 'bold');
  doc.text('SUBMISSION DATE:', pageWidth / 2, 110);
  doc.setFont('helvetica', 'normal');
  doc.text(submissionDate ? new Date(submissionDate).toLocaleString() : new Date().toLocaleString(), (pageWidth / 2) + 115, 110);

  doc.setFont('helvetica', 'bold');
  doc.text('STATUS:', pageWidth / 2, 126);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(status === 'Approved' ? 22 : (status === 'Rejected' ? 220 : 217), status === 'Approved' ? 163 : (status === 'Rejected' ? 38 : 119), status === 'Approved' ? 74 : (status === 'Rejected' ? 38 : 6));
  doc.text(String(status).toUpperCase(), (pageWidth / 2) + 55, 126);

  // Table Column Headers
  const defaultCriteria = [
    { key: 'round1', name: 'R1' },
    { key: 'round2', name: 'R2' },
    { key: 'round3', name: 'R3' },
    { key: 'technical', name: 'Tech' },
    { key: 'creativity', name: 'Creat' },
    { key: 'execution', name: 'Exec' },
  ];
  const criteria = scoringCriteria.length > 0 ? scoringCriteria : defaultCriteria;

  const tableHeaders = [
    'Rank',
    'Reg No',
    'Team Name',
    'College',
    'Leader',
    'Participants & USN',
    ...criteria.map(c => c.name),
    'Total Score',
    'Remarks',
  ];

  // Table Rows
  const tableData = teams.map((team, index) => {
    const leaderStr = `${team.leaderName} (${team.leaderUsn})`;
    const partsStr = (team.participants || [])
      .map(p => `${p.name} [${p.usn}]`)
      .join(', ');

    const row = [
      team.rank || index + 1,
      team.registrationNo || `IGN-T${index + 1}`,
      team.teamName,
      team.leaderCollege,
      leaderStr,
      partsStr || '—',
    ];

    criteria.forEach(c => {
      const val = team.scores ? team.scores[c.key] : 0;
      row.push(val !== undefined && val !== null ? val : '0');
    });

    row.push(team.totalScore !== undefined ? `${team.totalScore} pts` : '0 pts');
    row.push(team.remarks || '—');

    return row;
  });

  autoTable(doc, {
    startY: 155,
    head: [tableHeaders],
    body: tableData,
    theme: 'grid',
    styles: {
      fontSize: 8,
      cellPadding: 5,
      textColor: [30, 41, 59],
      lineColor: [226, 232, 240],
      lineWidth: 0.5,
    },
    headStyles: {
      fillColor: [15, 23, 42],
      textColor: [248, 250, 252],
      fontStyle: 'bold',
      halign: 'center',
    },
    columnStyles: {
      0: { halign: 'center', fontStyle: 'bold', width: 35 },
      1: { halign: 'center', width: 65 },
      2: { fontStyle: 'bold' },
      4: { fontStyle: 'italic' },
      [tableHeaders.length - 2]: { halign: 'center', fontStyle: 'bold', textColor: [217, 119, 6] },
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    margin: { left: 40, right: 40 },
    didDrawPage: (data) => {
      // Signature lines on final page
      const pageHeight = doc.internal.pageSize.getHeight();
      doc.setFontSize(8);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(100, 116, 139);

      // Footer
      doc.text(
        'Generated by IGNITRON 2K26 Event Management System · Official Copy · All Rights Reserved © 2026 GM University',
        40,
        pageHeight - 20
      );
      doc.text(
        `Page ${data.pageNumber} of ${doc.internal.getNumberOfPages()}`,
        pageWidth - 40,
        pageHeight - 20,
        { align: 'right' }
      );
    },
  });

  // Verification & Signatures section
  const finalY = (doc.lastAutoTable?.finalY || 200) + 30;
  if (finalY + 50 < doc.internal.pageSize.getHeight() - 40) {
    doc.setDrawColor(203, 213, 225);
    doc.line(60, finalY + 30, 200, finalY + 30);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.setTextColor(71, 85, 105);
    doc.text('Event Coordinator Signature', 75, finalY + 45);

    doc.line(pageWidth - 220, finalY + 30, pageWidth - 80, finalY + 30);
    doc.text('Faculty Convener / Dean', pageWidth - 200, finalY + 45);
  }

  doc.save(`Ignitron2K26_${eventName.replace(/\s+/g, '_')}_Coordinator_Report.pdf`);
}

// Generate Super Admin Official Approved Result Report PDF
export function generateAdminFinalReportPDF({
  submission,
  eventName,
  coordinatorName,
  approvedBy,
  approvedAt,
  teams = [],
  scoringCriteria = [],
}) {
  const doc = new jsPDF({
    orientation: 'landscape',
    unit: 'pt',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();

  // Header Banner
  doc.setFillColor(15, 23, 42); // Deep Slate
  doc.rect(0, 0, pageWidth, 80, 'F');

  // Accent Gold Border
  doc.setFillColor(16, 185, 129); // Emerald Approved Accent
  doc.rect(0, 77, pageWidth, 3, 'F');

  // Titles
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.setTextColor(245, 158, 11);
  doc.text('IGNITRON 2K26', 40, 36);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(148, 163, 184);
  doc.text('GM UNIVERSITY · GMUSA · CENTRAL EVENT MANAGEMENT COUNCIL', 40, 52);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(52, 211, 153);
  doc.text('OFFICIAL VERIFIED RESULT & AWARD NOTIFICATION', pageWidth - 40, 42, { align: 'right' });

  // Metadata Card
  doc.setFillColor(241, 245, 249);
  doc.roundedRect(40, 95, pageWidth - 80, 55, 4, 4, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.setTextColor(15, 23, 42);
  doc.text('EVENT:', 55, 115);
  doc.setFont('helvetica', 'normal');
  doc.text(eventName || submission?.eventName || 'N/A', 105, 115);

  doc.setFont('helvetica', 'bold');
  doc.text('COORDINATOR:', 55, 133);
  doc.setFont('helvetica', 'normal');
  doc.text(coordinatorName || submission?.coordinatorName || 'Assigned Coordinator', 145, 133);

  doc.setFont('helvetica', 'bold');
  doc.text('APPROVED BY:', pageWidth / 2, 115);
  doc.setFont('helvetica', 'normal');
  doc.text(approvedBy || submission?.approvedBy || 'Super Admin', (pageWidth / 2) + 95, 115);

  doc.setFont('helvetica', 'bold');
  doc.text('APPROVAL DATE:', pageWidth / 2, 133);
  doc.setFont('helvetica', 'normal');
  doc.text(approvedAt ? new Date(approvedAt).toLocaleString() : new Date().toLocaleString(), (pageWidth / 2) + 105, 133);

  // Table Data
  const defaultCriteria = [
    { key: 'round1', name: 'R1' },
    { key: 'round2', name: 'R2' },
    { key: 'round3', name: 'R3' },
    { key: 'technical', name: 'Tech' },
    { key: 'creativity', name: 'Creat' },
    { key: 'execution', name: 'Exec' },
  ];
  const criteria = scoringCriteria.length > 0 ? scoringCriteria : defaultCriteria;

  const tableHeaders = [
    'Rank',
    'Award',
    'Registration No',
    'Team Name',
    'College / Institute',
    'Team Leader',
    'Participants & USN',
    'Total Score',
    'Approval Status',
  ];

  const teamList = teams.length > 0 ? teams : (submission?.finalScores || []);

  const tableData = teamList.map((team, idx) => {
    const rank = team.rank || idx + 1;
    let award = 'Participant';
    if (rank === 1) award = 'Winner (1st)';
    else if (rank === 2) award = '1st Runner Up (2nd)';
    else if (rank === 3) award = '2nd Runner Up (3rd)';

    const partsStr = (team.participants || [])
      .map(p => `${p.name} (${p.usn})`)
      .join(', ');

    return [
      `#${rank}`,
      award,
      team.registrationNo || `IGN-${idx + 1}`,
      team.teamName,
      team.leaderCollege,
      `${team.leaderName} (${team.leaderUsn})`,
      partsStr || '—',
      `${team.totalScore} pts`,
      'APPROVED & PUBLISHED',
    ];
  });

  autoTable(doc, {
    startY: 165,
    head: [tableHeaders],
    body: tableData,
    theme: 'striped',
    styles: {
      fontSize: 8,
      cellPadding: 5,
      textColor: [30, 41, 59],
      lineColor: [226, 232, 240],
      lineWidth: 0.5,
    },
    headStyles: {
      fillColor: [15, 23, 42],
      textColor: [248, 250, 252],
      fontStyle: 'bold',
      halign: 'center',
    },
    columnStyles: {
      0: { halign: 'center', fontStyle: 'bold', width: 35 },
      1: { halign: 'center', fontStyle: 'bold', textColor: [217, 119, 6] },
      2: { halign: 'center', width: 80 },
      3: { fontStyle: 'bold' },
      7: { halign: 'center', fontStyle: 'bold', textColor: [16, 185, 129] },
      8: { halign: 'center', fontStyle: 'bold', textColor: [16, 185, 129], width: 100 },
    },
    margin: { left: 40, right: 40 },
    didDrawPage: (data) => {
      const pageHeight = doc.internal.pageSize.getHeight();
      doc.setFontSize(8);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(100, 116, 139);

      doc.text(
        'Generated by IGNITRON 2K26 Event Management System — Super Admin Official Copy',
        40,
        pageHeight - 20
      );
      doc.text(
        `Page ${data.pageNumber} of ${doc.internal.getNumberOfPages()}`,
        pageWidth - 40,
        pageHeight - 20,
        { align: 'right' }
      );
    },
  });

  // Official Stamp box
  const finalY = (doc.lastAutoTable?.finalY || 200) + 30;
  if (finalY + 60 < doc.internal.pageSize.getHeight() - 30) {
    doc.setDrawColor(16, 185, 129);
    doc.setLineWidth(1);
    doc.roundedRect(pageWidth - 250, finalY, 210, 50, 4, 4);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    doc.setTextColor(16, 185, 129);
    doc.text('IGNITRON 2K26 CENTRAL COUNCIL', pageWidth - 240, finalY + 18);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(71, 85, 105);
    doc.text(`Electronically Verified & Approved`, pageWidth - 240, finalY + 30);
    doc.text(`By: ${approvedBy || 'Super Admin'}`, pageWidth - 240, finalY + 42);
  }

  doc.save(`Ignitron2K26_${(eventName || 'Event').replace(/\s+/g, '_')}_Official_Approved_Results.pdf`);
}

