async function updateDB() {
  const uri = process.env.MONGODB_URI;
  if (!uri) {
    console.error('No MONGODB_URI found!');
    process.exit(1);
  }

  console.log('Connecting to MongoDB Atlas...');
  await mongoose.connect(uri);

  const eventsCollection = mongoose.connection.collection('events');
  console.log('Cleaning up old events and inserting 28 official events...');
  await eventsCollection.deleteMany({});

  const docs = officialEvents.map(e => ({
    id: e.id,
    name: e.name,
    time: e.time,
    day: e.day,
    venue: e.venue,
    category: e.category,
    club: e.club || '',
    description: e.description,
    rulebookLink: e.rulebookLink,
    registrationLink: e.registrationLink,
    maxTeamSize: e.maxTeamSize,
    isHackathon: !!e.isHackathon,
    scoringCriteria: e.isHackathon
      ? [
          { key: 'round1', name: 'Round 1', maxMarks: 50 },
          { key: 'round2', name: 'Round 2', maxMarks: 50 },
        ]
      : [{ key: 'marks', name: 'Score', maxMarks: 100 }],
    coordinatorId: '',
    coordinatorName: '',
    createdAt: new Date(),
  }));

  const result = await eventsCollection.insertMany(docs);
  console.log(`Successfully inserted ${result.insertedCount} events into MongoDB!`);
  await mongoose.disconnect();
}

updateDB().catch(err => {
  console.error('Error updating DB:', err);
  process.exit(1);
});

